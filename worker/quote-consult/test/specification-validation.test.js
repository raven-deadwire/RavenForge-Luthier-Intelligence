test('specification questions cover four known failure families in all three languages', () => {
  assert.equal(SPECIFICATION_CASES.length, 12);
  for (const family of ['xpure_power', 'edda_electronics', 'embla_default', 'gramr_fretboard']) {
    const cases = SPECIFICATION_CASES.filter(entry => entry.family === family);
    assert.deepEqual(cases.map(entry => entry.language).sort(), ['de', 'en', 'ko']);
    for (const entry of cases) {
      assert.equal(entry.request.language, entry.language);
      assert.equal(entry.request.messages.at(-1).role, 'user');
      if (family === 'embla_default') {
        assert.equal(entry.request.configuration.model, 'EDDA');
        assert.match(entry.request.messages[0].content, /EMBLA/);
      }
    }
  }
});

test('recorded old production replies remain negative evidence, never candidate live passes', () => {
  const records = recordedCases();
  assert.equal(records.length, 4);
  const expected = {
    xpure_power: 'xpure_9v_not_stated',
    edda_electronics: 'edda_eq01_not_distinguished',
    embla_default: 'embla_legacy_passive_standard',
    gramr_fretboard: 'gramr_exotic_navigation'
  };
  for (const entry of records) {
    assert.equal(entry.original.source_commit, '2546afa584d662243cd48646a9100dba387cc74d');
    const audit = evaluateSpecificationReply(entry.family, entry.language, entry.original.response.reply);
    assert.ok(audit.findings.some(finding => finding.code === expected[entry.family]), entry.id);
    assert.equal(audit.manual_review_required, true);
  }
});

