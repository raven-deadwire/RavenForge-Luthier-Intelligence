test('live validation without a key records a block and makes zero provider requests', () => {
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'rf-spec-no-key-'));
  const env = { ...process.env };
  delete env.OPENAI_API_KEY;
  try {
    const result = spawnSync(process.execPath, [fileURLToPath(new URL('../tools/validate-specifications.mjs', import.meta.url)),
      '--live', '--output', output], { env, encoding: 'utf8' });
    assert.equal(result.status, 2, result.stderr);
    const summary = JSON.parse(fs.readFileSync(path.join(output, 'summary.json'), 'utf8'));
    assert.equal(summary.status, 'blocked_missing_openai_api_key');
    assert.equal(summary.counts.openai_http_attempts, 0);
    assert.equal(summary.counts.openai_http_responses, 0);
    assert.equal(summary.counts.mock_requests, 0);
    assert.equal(summary.counts.completed_cases, 0);
    assert.equal(summary.semantic_quality, 'not_certified');
    assert.equal(summary.candidate.system_prompt_sha256, null);
  } finally { fs.rmSync(output, { recursive: true, force: true }); }
});
