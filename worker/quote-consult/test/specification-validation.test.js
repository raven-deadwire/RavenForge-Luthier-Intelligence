test('synthetic KO/EN/DE contradictions are flagged even when xPure and 9V are present', () => {
  const pairs = [
    ['ko', 'Delano xPure는 9V 버퍼지만 배터리 없이 사용할 수 있습니다.',
      'Delano xPure는 9V 전원이 필요하므로 배터리 없이 사용할 수 없습니다.'],
    ['en', 'The Delano xPure is a 9V buffer, but it is battery-free and can run without a battery.',
      'The Delano xPure requires 9V and cannot run without a battery.'],
    ['de', 'Der Delano xPure ist ein 9V-Buffer und benötigt keine Batterie.',
      'Der Delano xPure benötigt 9V und kann nicht ohne Batterie betrieben werden.']
  ];
  for (const [language, incorrect, correct] of pairs) {
    const bad = evaluateSpecificationReply('xpure_power', language, incorrect);
    assert.ok(bad.findings.some(finding => finding.code === 'xpure_battery_free_assertion'), language);
    assert.deepEqual(evaluateSpecificationReply('xpure_power', language, correct).findings, [], language);
    assert.equal(bad.manual_review_required, true);
  }
});

